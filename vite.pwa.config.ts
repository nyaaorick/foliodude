import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import path from 'node:path';
import type { Plugin } from 'vite';

/**
 * Standalone PWA build (iOS Safari "Add to Home Screen").
 *
 * Shares every source file with the WXT extension build — only the HTML shell,
 * the manifest, and the router mode differ. WXT owns `entrypoints/`; this owns
 * `pwa/`. Output lands next to the extension build under `.output/`.
 *
 * `base: './'` keeps the bundle host-agnostic, so the same artifact works at a
 * domain root, a Cloudflare Pages preview URL, or a project subpath.
 */
/**
 * Emits the PWA service worker with the built asset names baked in.
 *
 * A hand-written precache list would go stale on every build, because Vite
 * content-hashes filenames. Reading the bundle instead means the shell is
 * always precached in full — which is what makes the app open offline on iOS,
 * where an app-shell precache is the only offline mechanism available
 * (PLAN.md §5 Phase 3).
 */
function serviceWorker(): Plugin {
  return {
    name: 'foliodude-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle)
        // Source maps are large and only ever loaded by devtools on demand.
        .filter((name) => !name.endsWith('.map'))
        // PGlite's WASM and data files are ~16MB together. `cache.addAll()` is
        // all-or-nothing, so precaching them would push install over iOS's
        // storage quota and fail the whole registration — leaving no offline
        // support at all. The fetch handler caches them on first real use
        // instead, which happens on the first query of the first launch.
        .filter((name) => !/\.(wasm|data)$/.test(name))
        .map((name) => `./${name}`);

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: buildServiceWorker(['./', './index.html', ...assets]),
      });
    },
  };
}

function buildServiceWorker(precache: string[]) {
  return `// Generated by vite.pwa.config.ts — do not edit.
const CACHE = 'foliodude-${Date.now()}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  // One cache per build; drop every older one so a stale shell cannot survive.
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  // Navigations always resolve to the cached shell. The app is a HashRouter, so
  // every route is the same document, and this is what lets a home-screen launch
  // work with no network at all.
  if (request.mode === 'navigate') {
    event.respondWith(caches.match('./index.html').then((cached) => cached ?? fetch(request)));
    return;
  }

  if (new URL(request.url).origin !== self.location.origin) return;

  // Cache-first: filenames are content-hashed, so a hit is never stale.
  event.respondWith(
    caches.match(request).then((cached) => cached ?? fetch(request).then((response) => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    })),
  );
});
`;
}

export default defineConfig({
  root: path.resolve(__dirname, 'pwa'),
  base: './',
  publicDir: path.resolve(__dirname, 'pwa/public'),
  plugins: [react(), tailwindcss(), serviceWorker()],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, '.'),
    },
  },
  build: {
    outDir: path.resolve(__dirname, '.output/pwa'),
    emptyOutDir: true,
    target: 'safari16',
    sourcemap: true,
  },
  server: {
    host: true,
    port: 5174,
  },
});
